-- 0014 tamper-evident audit trail, anomaly detection and alerts.
--
-- What is recorded
--   * automatically, by triggers (so no code path can forget): membership added / role changed / removed, project created / verified
--     changed / deleted, Search Console token connected / replaced / disconnected, organisation settings changed
--   * by the server through audit_record(): access denied, competitor added, a daily run requested, sign-in to Search Console started
--   Sign-ins themselves are recorded by Supabase Auth (Dashboard > Logs > Auth), not here.
-- How it resists tampering
--   * append only: UPDATE, DELETE and TRUNCATE are refused by triggers, and no role except the owner has write privileges
--   * hash chain: every row stores the hash of the previous row; audit_verify() recomputes the chain and reports the first broken row
--   * the head hash (audit_head()) is sent to an external place by the daily monitor (ALERT_WEBHOOK_URL), so rewriting the whole table
--     would not match what was already sent out
-- This is tamper-EVIDENT, not tamper-proof: the database owner can still alter data; the chain and the external head make that visible.
-- Additive. Server-only writes. Never edit once applied.

-- 1. The trail ------------------------------------------------------------------------------------------------------------------
create table if not exists public.audit_log (
  id              bigint generated by default as identity primary key,
  at              timestamptz not null,
  organisation_id uuid,          -- no foreign key: the trail must outlive the things it describes
  actor           uuid,          -- null = the system / service role
  action          text not null check (char_length(action) between 1 and 80),
  target_type     text,
  target_id       text,
  detail          jsonb not null default '{}'::jsonb,
  prev_hash       text not null,
  hash            text not null
);
alter table public.audit_log enable row level security;
create index if not exists audit_log_org_at on public.audit_log (organisation_id, at desc);
create index if not exists audit_log_action_at on public.audit_log (action, at desc);
create index if not exists audit_log_actor_at on public.audit_log (actor, at desc) where actor is not null;

create or replace function public.audit_row_hash(prev text, rid bigint, at_ timestamptz, org uuid, actor_ uuid, action_ text, ttype text, tid text, detail_ jsonb)
returns text language sql immutable
as $$ select encode(sha256(convert_to(concat_ws('|', prev, rid::text, to_char(at_ at time zone 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.US'), coalesce(org::text, ''), coalesce(actor_::text, ''), action_, coalesce(ttype, ''), coalesce(tid, ''), detail_::text), 'utf8')), 'hex') $$;

-- Drops keys that could carry secrets, so a careless caller cannot put one into the trail.
create or replace function public.audit_clean(d jsonb)
returns jsonb language sql immutable
as $$
  select coalesce(jsonb_object_agg(k, v), '{}'::jsonb)
  from jsonb_each(case when jsonb_typeof(d) = 'object' then d else '{}'::jsonb end) as e(k, v)
  where k !~* '(token|secret|password|passwd|authorization|api[_-]?key|private)'
$$;

-- The only way to add a row. One writer at a time (advisory lock) so the chain has a single order.
create or replace function public.audit_record(p_org uuid, p_actor uuid, p_action text, p_target_type text default null, p_target_id text default null, p_detail jsonb default '{}'::jsonb)
returns bigint language plpgsql volatile security definer set search_path = public, pg_temp
as $$
declare prev text; rid bigint; ts timestamptz := clock_timestamp(); d jsonb := public.audit_clean(p_detail);
begin
  perform pg_advisory_xact_lock(7446014);
  select hash into prev from public.audit_log order by id desc limit 1;
  prev := coalesce(prev, repeat('0', 64));
  rid := nextval(pg_get_serial_sequence('public.audit_log', 'id'));
  insert into public.audit_log (id, at, organisation_id, actor, action, target_type, target_id, detail, prev_hash, hash)
  values (rid, ts, p_org, p_actor, p_action, p_target_type, p_target_id, d, prev,
          public.audit_row_hash(prev, rid, ts, p_org, p_actor, p_action, p_target_type, p_target_id, d));
  return rid;
end $$;

-- Append only.
create or replace function public.audit_log_immutable() returns trigger language plpgsql as $$
begin raise exception 'The audit log is append-only' using errcode = 'insufficient_privilege'; end $$;
drop trigger if exists audit_log_no_change on public.audit_log;
create trigger audit_log_no_change before update or delete on public.audit_log for each row execute function public.audit_log_immutable();
drop trigger if exists audit_log_no_truncate on public.audit_log;
create trigger audit_log_no_truncate before truncate on public.audit_log for each statement execute function public.audit_log_immutable();

-- Recomputes the whole chain. Returns the first row that does not match (null = intact) and how many rows were checked.
create or replace function public.audit_verify()
returns table (first_bad_id bigint, checked bigint) language plpgsql stable security definer set search_path = public, pg_temp
as $$
declare r public.audit_log; prev text := repeat('0', 64); n bigint := 0;
begin
  for r in select * from public.audit_log order by id loop
    n := n + 1;
    if r.prev_hash <> prev or r.hash <> public.audit_row_hash(r.prev_hash, r.id, r.at, r.organisation_id, r.actor, r.action, r.target_type, r.target_id, r.detail) then
      first_bad_id := r.id; checked := n; return next; return;
    end if;
    prev := r.hash;
  end loop;
  first_bad_id := null; checked := n; return next;
end $$;

create or replace function public.audit_head()
returns table (id bigint, hash text) language sql stable security definer set search_path = public, pg_temp
as $$ select l.id, l.hash from public.audit_log l order by l.id desc limit 1 $$;

-- 2. Automatic recording ---------------------------------------------------------------------------------------------------------
create or replace function public.audit_members() returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    perform public.audit_record(new.organisation_id, (select auth.uid()), 'member.added', 'user', new.user_id::text, jsonb_build_object('role', new.role));
  elsif tg_op = 'UPDATE' then
    if old.role is distinct from new.role then
      perform public.audit_record(new.organisation_id, (select auth.uid()), 'member.role_changed', 'user', new.user_id::text, jsonb_build_object('from', old.role, 'to', new.role));
    end if;
  else
    perform public.audit_record(old.organisation_id, (select auth.uid()), 'member.removed', 'user', old.user_id::text, jsonb_build_object('role', old.role));
  end if;
  return null;
end $$;
drop trigger if exists audit_members on public.organisation_members;
create trigger audit_members after insert or update or delete on public.organisation_members for each row execute function public.audit_members();

create or replace function public.audit_projects() returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
begin
  if tg_op = 'INSERT' then
    perform public.audit_record(new.organisation_id, (select auth.uid()), 'project.created', 'project', new.id::text, jsonb_build_object('domain', new.domain));
  elsif tg_op = 'UPDATE' then
    if old.verified is distinct from new.verified then
      perform public.audit_record(new.organisation_id, (select auth.uid()), 'project.verified_changed', 'project', new.id::text, jsonb_build_object('from', old.verified, 'to', new.verified));
    end if;
  else
    perform public.audit_record(old.organisation_id, (select auth.uid()), 'project.deleted', 'project', old.id::text, jsonb_build_object('domain', old.domain));
  end if;
  return null;
end $$;
drop trigger if exists audit_projects on public.projects;
create trigger audit_projects after insert or update or delete on public.projects for each row execute function public.audit_projects();

-- Search Console tokens. The token value itself is never recorded.
create or replace function public.audit_gsc_tokens() returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
declare pid uuid := coalesce(new.project_id, old.project_id); org uuid;
begin
  select organisation_id into org from public.projects where id = pid;
  perform public.audit_record(org, (select auth.uid()),
    case tg_op when 'INSERT' then 'gsc.connected' when 'UPDATE' then 'gsc.token_replaced' else 'gsc.disconnected' end, 'project', pid::text, '{}'::jsonb);
  return null;
end $$;
drop trigger if exists audit_gsc_tokens on public.gsc_tokens;
create trigger audit_gsc_tokens after insert or update of token_enc or delete on public.gsc_tokens for each row execute function public.audit_gsc_tokens();

-- Organisation settings (name, type and anything added later): which columns changed, never secrets.
create or replace function public.audit_organisations() returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
declare changed jsonb;
begin
  select coalesce(jsonb_object_agg(n.key, jsonb_build_object('from', o.value, 'to', n.value)), '{}'::jsonb) into changed
  from jsonb_each(to_jsonb(new)) n join jsonb_each(to_jsonb(old)) o using (key) where n.value is distinct from o.value;
  if changed <> '{}'::jsonb then perform public.audit_record(new.id, (select auth.uid()), 'organisation.updated', 'organisation', new.id::text, changed); end if;
  return null;
end $$;
drop trigger if exists audit_organisations on public.organisations;
create trigger audit_organisations after update on public.organisations for each row execute function public.audit_organisations();

-- 3. Alerts ---------------------------------------------------------------------------------------------------------------------------
-- One row per (kind, organisation, subject, day): the same condition does not raise the same alert twice in a day.
create table if not exists public.alerts (
  id              bigint generated always as identity primary key,
  created_at      timestamptz not null default now(),
  day             date not null default current_date,
  kind            text not null,
  severity        text not null default 'warning' check (severity in ('info', 'warning', 'critical')),
  organisation_id uuid,
  subject         text not null default '',
  detail          jsonb not null default '{}'::jsonb,
  notified_at     timestamptz
);
alter table public.alerts enable row level security;
create unique index if not exists alerts_once_per_day on public.alerts (kind, coalesce(organisation_id, '00000000-0000-0000-0000-000000000000'::uuid), subject, day);
create index if not exists alerts_unsent on public.alerts (created_at) where notified_at is null;

-- 4. Unusual access patterns -----------------------------------------------------------------------------------------------------------
create or replace function public.audit_anomalies(p_window interval default interval '1 hour')
returns table (kind text, severity text, organisation_id uuid, subject text, n bigint, detail jsonb)
language sql stable security definer set search_path = public, pg_temp
as $$
  with recent as (select * from public.audit_log where at > now() - p_window)
  -- many membership changes in one organisation
  select 'many_membership_changes', 'warning', r.organisation_id, ''::text, count(*), jsonb_build_object('window', p_window::text)
    from recent r where r.action in ('member.added', 'member.role_changed', 'member.removed') group by r.organisation_id having count(*) > 10
  union all
  -- anyone made or demoted an owner
  select 'owner_changed', 'critical', r.organisation_id, r.target_id, count(*), r.detail
    from recent r where r.action = 'member.role_changed' and (r.detail->>'to' = 'owner' or r.detail->>'from' = 'owner') group by r.organisation_id, r.target_id, r.detail
  union all
  -- one person repeatedly refused: probing for other people's projects
  select 'access_probing', 'warning', null::uuid, r.actor::text, count(*), jsonb_build_object('window', p_window::text)
    from recent r where r.action = 'access.denied' and r.actor is not null group by r.actor having count(*) > 20
  union all
  -- Search Console accounts being (re)connected in bulk
  select 'many_gsc_connections', 'warning', r.organisation_id, ''::text, count(*), jsonb_build_object('window', p_window::text)
    from recent r where r.action in ('gsc.connected', 'gsc.token_replaced') group by r.organisation_id having count(*) > 5
  union all
  -- projects deleted in bulk
  select 'many_projects_deleted', 'critical', r.organisation_id, ''::text, count(*), jsonb_build_object('window', p_window::text)
    from recent r where r.action = 'project.deleted' group by r.organisation_id having count(*) > 3
$$;

-- Turns anomalies (and a broken audit chain) into alert rows. Returns how many NEW alerts were raised. Run by the daily monitor.
create or replace function public.monitor_run()
returns int language plpgsql volatile security definer set search_path = public, pg_temp
as $$
declare n int := 0; added int; bad bigint;
begin
  insert into public.alerts (kind, severity, organisation_id, subject, detail)
  select a.kind, a.severity, a.organisation_id, a.subject, a.detail || jsonb_build_object('count', a.n) from public.audit_anomalies(interval '24 hours') a
  on conflict do nothing;
  get diagnostics added = row_count; n := n + added;
  select v.first_bad_id into bad from public.audit_verify() v;
  if bad is not null then
    insert into public.alerts (kind, severity, subject, detail) values ('audit_chain_broken', 'critical', bad::text, jsonb_build_object('first_bad_id', bad)) on conflict do nothing;
    get diagnostics added = row_count; n := n + added;
  end if;
  return n;
end $$;

-- 5. Privileges ----------------------------------------------------------------------------------------------------------------------------
-- Owners and admins of an organisation can read their organisation's trail. Nobody can write through the API.
drop policy if exists audit_log_select on public.audit_log;
create policy audit_log_select on public.audit_log for select to authenticated using (organisation_id is not null and public.org_role(organisation_id) in ('owner', 'admin'));
revoke all on public.audit_log, public.alerts from public, anon, authenticated;
grant select on public.audit_log to authenticated;
grant select on public.audit_log to service_role;
grant select, insert, update on public.alerts to service_role;
revoke all on function public.audit_record(uuid, uuid, text, text, text, jsonb), public.audit_verify(), public.audit_head(), public.audit_anomalies(interval), public.monitor_run(),
  public.audit_row_hash(text, bigint, timestamptz, uuid, uuid, text, text, text, jsonb), public.audit_clean(jsonb) from public, anon, authenticated;
grant execute on function public.audit_record(uuid, uuid, text, text, text, jsonb), public.audit_verify(), public.audit_head(), public.audit_anomalies(interval), public.monitor_run() to service_role;
